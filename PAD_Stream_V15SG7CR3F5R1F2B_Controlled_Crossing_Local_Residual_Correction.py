def all_crossings(profile, xi, threshold=THRESHOLD):
    p = np.asarray(profile, dtype=float)
    x = np.asarray(xi, dtype=float)
    y = p - threshold

    crossings = []

    for i in range(len(y) - 1):
        y0 = y[i]
        y1 = y[i + 1]

        if not np.isfinite(y0) or not np.isfinite(y1):
            continue

        if y0 == 0.0:
            crossings.append(float(x[i]))
            continue

        if y0 * y1 < 0.0 or y1 == 0.0:
            denom = y1 - y0

            if abs(denom) <= EPS:
                xc = 0.5 * (x[i] + x[i + 1])
            else:
                frac = -y0 / denom
                xc = x[i] + frac * (x[i + 1] - x[i])

            crossings.append(float(xc))

    return np.asarray(crossings, dtype=float)


def first_physical_crossing(profile, xi):
    crossings = all_crossings(profile, xi)

    if crossings.size == 0:
        return np.nan, 0

    return float(crossings[0]), int(crossings.size)


def crossing_distance_field(truth, xi):
    nstream, _ = truth.shape

    front_x = np.full(nstream, np.nan, dtype=float)
    crossing_count = np.zeros(nstream, dtype=int)

    for s in range(nstream):
        fx, count = first_physical_crossing(
            truth[s],
            xi,
        )

        front_x[s] = fx
        crossing_count[s] = count

    distance = np.full_like(
        truth,
        np.inf,
        dtype=float,
    )

    valid = np.isfinite(front_x)

    for s in np.where(valid)[0]:
        distance[s] = np.abs(
            xi - front_x[s]
        )

    return front_x, crossing_count, distance


def matched_crossing(reference_profile, candidate_profile, xi):
    ref = all_crossings(
        reference_profile,
        xi,
    )

    cand = all_crossings(
        candidate_profile,
        xi,
    )

    if ref.size == 0 or cand.size == 0:
        return np.nan, np.nan, ref.size, cand.size

    ref_x = ref[0]

    j = int(
        np.argmin(
            np.abs(
                cand - ref_x
            )
        )
    )

    return (
        float(ref_x),
        float(cand[j]),
        int(ref.size),
        int(cand.size),
    )


def front_metrics(truth, candidate, frozen, xi):
    nstream = truth.shape[0]

    errors = []
    frozen_shifts = []
    recovered = 0
    multiple = 0

    for s in range(nstream):

        tx, cx, _, nc = matched_crossing(
            truth[s],
            candidate[s],
            xi,
        )

        _, fx, _, _ = matched_crossing(
            truth[s],
            frozen[s],
            xi,
        )

        if nc > 1:
            multiple += 1

        if np.isfinite(tx) and np.isfinite(cx):
            recovered += 1
            errors.append(
                abs(
                    cx - tx
                )
            )

            if np.isfinite(fx):
                frozen_shifts.append(
                    abs(
                        cx - fx
                    )
                )

    if not errors:
        return {
            "recovered_fronts": 0,
            "conditioned_front_gap": np.inf,
            "SG7A_front_P90": np.inf,
            "SG7A_front_mean": np.inf,
            "frozen_relative_P90": np.inf,
            "multiple_crossing_fraction": 1.0,
        }

    errors = np.asarray(
        errors,
        dtype=float,
    )

    return {
        "recovered_fronts":
            int(recovered),

        "conditioned_front_gap":
            float(
                np.mean(
                    errors
                )
            ),

        "SG7A_front_P90":
            float(
                np.percentile(
                    errors,
                    90,
                )
            ),

        "SG7A_front_mean":
            float(
                np.mean(
                    errors
                )
            ),

        "frozen_relative_P90":
            float(
                np.percentile(
                    frozen_shifts,
                    90,
                )
            )
            if frozen_shifts
            else np.nan,

        "multiple_crossing_fraction":
            float(
                multiple
                /
                nstream
            ),
    }


