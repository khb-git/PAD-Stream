def build_crossing_local_gamma(
    truth,
    tau_end,
    guard_mask,
    *,
    mid_gamma,
    slow_gamma,
    very_slow_gamma,
    tail_gamma,
):
    """
    Build third-stage gamma outside the selected crossing-distance guard.

    Priority:
      1. TOF band defines base gamma.
      2. Tail may increase base gamma.
      3. Guard forces gamma = 0 exactly.
    """

    nstream, _ = truth.shape

    gamma = np.zeros_like(
        truth,
        dtype=float,
    )

    stream_gamma = np.zeros(
        nstream,
        dtype=float,
    )

    stream_gamma[
        tau_end <= 500.0
    ] = 0.0

    stream_gamma[
        (tau_end > 500.0)
        &
        (tau_end <= 1000.0)
    ] = mid_gamma

    stream_gamma[
        (tau_end > 1000.0)
        &
        (tau_end <= 2000.0)
    ] = slow_gamma

    stream_gamma[
        tau_end > 2000.0
    ] = very_slow_gamma

    gamma[:] = stream_gamma[:, None]

    tail_mask = truth <= 0.22

    gamma[
        tail_mask
    ] = np.maximum(
        gamma[
            tail_mask
        ],
        tail_gamma,
    )

    gamma[
        guard_mask
    ] = 0.0

    return np.clip(
        gamma,
        0.0,
        1.0,
    )


