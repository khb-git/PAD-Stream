def tof_band_mask(tau_end, lo, hi):
    return (
        (tau_end > lo)
        &
        (tau_end <= hi)
    )


def tof_metrics(truth, pred, tau_end):
    diff = pred - truth

    def band(lo, hi):
        smask = tof_band_mask(
            tau_end,
            lo,
            hi,
        )

        if not np.any(smask):
            return np.nan, np.nan, 0

        local = diff[
            smask
        ]

        return (
            float(
                np.mean(
                    local
                )
            ),
            float(
                np.mean(
                    np.abs(
                        local
                    )
                )
            ),
            int(
                np.sum(
                    smask
                )
            ),
        )

    b500, l1500, n500 = band(
        500.0,
        1000.0,
    )

    b1000, l11000, n1000 = band(
        1000.0,
        2000.0,
    )

    b2000, l12000, n2000 = band(
        2000.0,
        np.inf,
    )

    tail_mask = truth <= 0.22

    tail_bias = (
        float(
            np.mean(
                diff[
                    tail_mask
                ]
            )
        )
        if np.any(
            tail_mask
        )
        else np.nan
    )

    mask500 = tof_band_mask(
        tau_end,
        500.0,
        1000.0,
    )

    material_share = (
        float(
            np.mean(
                diff[
                    mask500
                ]
                >
                MATERIAL_POSITIVE_THRESHOLD
            )
        )
        if np.any(
            mask500
        )
        else np.nan
    )

    return {
        "bias_500_1000":
            b500,
        "L1_500_1000":
            l1500,
        "streamlines_500_1000":
            n500,

        "bias_1000_2000":
            b1000,
        "L1_1000_2000":
            l11000,
        "streamlines_1000_2000":
            n1000,

        "bias_gt2000":
            b2000,
        "L1_gt2000":
            l12000,
        "streamlines_gt2000":
            n2000,

        "tail_bias":
            tail_bias,

        "material_positive_share_500_1000":
            material_share,
    }


