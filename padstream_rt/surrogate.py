"""Learned speciation + exact kinetics: the ML chemistry surrogate.

What is learned, and what is not
--------------------------------
The expensive part of a kinetic chemistry call is speciation (pH and the
saturation index of every mineral from the element totals); PHREEQC does it
with a Newton solve per cell.  The rate law itself (Palandri & Kharaka 2004,
kinetics.py) is cheap and is evaluated exactly.  So the surrogate learns only

    (log10 molalities of the transported elements, T, P)  ->  (pH, SI_1..SI_n)

and the kinetic extent is   xi = r(k(T, pH), A, Omega = 10^SI) * V_bulk * dt,
followed by a learned-Omega overshoot limiter.  The surrogate always returns
mineral extents xi, so element conservation is exact by construction
(chemistry.py); what can go wrong is pH/SI error, which the SurrogateBackend
checks catch (positivity, overshoot) and send to the PHREEQC reference.

Training states are generated by reaction-path sampling with PHREEQC itself
(``sample_states``): a NaCl brine at (T, P) is equilibrated with CO2 (or given
a dissolved-carbon total), the primary minerals are partly dissolved by random
extents, and secondary phases may precipitate.  The states are therefore
chemically reachable rather than random points in composition space.

The regressor is a plain NumPy MLP (no torch / scikit-learn dependency at run
time); ``fit_mlp`` trains it with Adam.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, List, Optional, Sequence

import numpy as np

from .chemistry import ChemInput
from .kinetics import mineral_rate

ATM = 101325.0
LOG_FLOOR = -14.0
TRACE_MOLAL = 1e-7


# ----------------------------------------------------------------------
# 1. Training data
# ----------------------------------------------------------------------
@dataclass
class SamplingRanges:
    T_C: tuple = (35.0, 75.0)
    P_bar: tuple = (100.0, 250.0)
    nacl_molal: tuple = (0.3, 3.5)
    log_pco2_atm: tuple = (-1.5, 2.1)          # injected / reacting brine
    log_pco2_formation: tuple = (-2.5, 0.0)    # pre-injection formation brine
    p_mixing: float = 0.6                       # share of mixing-path samples
    p_co2_phase: float = 0.75                   # path samples: else dissolved CO2 added
    log_c_free: tuple = (-4.0, -0.5)
    p_include_mineral: float = 0.8
    p_secondary_eq: float = 0.5                 # allow secondary phases to precipitate
    log_extent: tuple = (-8.0, -2.0)            # mol/kgw dissolved along the path


def trace_elements(elements):
    """Elements given a trace background (all but Na, Cl, C; Fe as Fe(2))."""
    return [{"Fe": "Fe(2)"}.get(e, e) for e in elements if e not in ("Na", "Cl", "C")]


def _soln(k, T, P, nacl, trace=("K", "Mg", "Fe(2)", "Al", "Si")):
    s = [f"SOLUTION {k}", f" temp {T:.4f}", f" pressure {P / ATM:.4f}", " units mol/kgw",
         " pH 7 charge", f" Na {nacl:.6g}", f" Cl {nacl:.6g}"]
    # trace background so that every SI is defined (real brines always carry these)
    return s + [f" {e} {TRACE_MOLAL:g}" for e in trace]


def _sample_input(k, rng, r: SamplingRanges, primaries, formation_eq, secondaries, trace):
    """PHREEQC input for sample k; only its last simulation is written out.

    path:   NaCl brine (+ CO2 gas or dissolved CO2) -> partial dissolution of
            the primaries -> optional secondary precipitation.
    mixing: formation brine equilibrated with ``formation_eq`` at low pCO2,
            mixed with CO2-saturated injected brine, then partial dissolution
            and optional secondary precipitation (a displacement front).
    """
    T = rng.uniform(*r.T_C); P = rng.uniform(*r.P_bar) * 1e5; nacl = rng.uniform(*r.nacl_molal)
    ext = [10 ** rng.uniform(*r.log_extent) if rng.random() < r.p_include_mineral else 0.0
           for _ in primaries]
    sec = list(secondaries) if rng.random() < r.p_secondary_eq else []
    off = " -active false"
    on = " -active true"
    base = 3 * k
    out = []
    if rng.random() < r.p_mixing:
        out += ["SELECTED_OUTPUT", off] + _soln(base + 1, T, P, nacl, trace)
        out += [f"EQUILIBRIUM_PHASES {base + 1}", f" CO2(g) {rng.uniform(*r.log_pco2_formation):.5f} 100"]
        out += [f" {ph} 0 10" for ph in formation_eq] + [f"SAVE solution {base + 1}", "END"]
        out += _soln(base + 2, T, P, nacl, trace)
        out += [f"EQUILIBRIUM_PHASES {base + 2}", f" CO2(g) {rng.uniform(*r.log_pco2_atm):.5f} 100",
                f"SAVE solution {base + 2}", "END"]
        f = rng.uniform(0.0, 1.0)
        out += ["SELECTED_OUTPUT", on, f"MIX {base + 3}", f" {base + 1} {f:.6f}", f" {base + 2} {1 - f:.6f}"]
        eq = [f" {ph} 0 0" for ph in sec]
    else:
        out += ["SELECTED_OUTPUT", on] + _soln(base + 3, T, P, nacl, trace)
        eq = [f" {ph} 0 0" for ph in sec]
        if rng.random() < r.p_co2_phase:
            eq.insert(0, f" CO2(g) {rng.uniform(*r.log_pco2_atm):.5f} 100")
        else:
            ext = ext + [10 ** rng.uniform(*r.log_c_free)]
    if eq:
        out += [f"EQUILIBRIUM_PHASES {base + 3}"] + eq
    names = list(primaries) + (["CO2"] if len(ext) > len(primaries) else [])
    rx = [(ph, x) for ph, x in zip(names, ext) if x > 0]
    if rx:
        out += [f"REACTION {base + 3}"] + [f" {ph} {x:.6g}" for ph, x in rx] + [" 1 mol"]
    out.append("END")
    return "\n".join(out)


def sample_states(backend, n: int, rng: np.random.Generator,
                  primaries: Sequence[str], secondaries: Sequence[str] = (),
                  formation_eq: Sequence[str] = ("Quartz", "K-feldspar", "Kaolinite"),
                  ranges: SamplingRanges = SamplingRanges(), chunk: int = 300):
    """Reaction-path and mixing samples labelled by PHREEQC.

    Returns dict with ``X`` (n, ne+2) = [log10 molality of each element, T (K),
    P (Pa)] and ``Y`` (n, 1+nphase) = [pH, SI of each backend phase].
    """
    from .phreeqc_backend import _phreeqc
    els, phases = backend.elements, backend.phases
    X, Y = [], []
    head = ("SELECTED_OUTPUT\n -reset false\n -simulation true\n -state true\n -temperature true\n"
            " -pH true\n -saturation_indices " + " ".join(phases) + "\n"
            "USER_PUNCH\n -headings " + " ".join(f"m_{e}" for e in els) + " P\n"
            + "\n".join(f"{10 + i} PUNCH TOT(\"{e}\")" for i, e in enumerate(els))
            + f"\n{10 + len(els)} PUNCH PRESSURE\n")
    done = 0
    while done < n:
        m = min(chunk, n - done)
        tr = trace_elements(els)
        inp = head + "\n".join(_sample_input(k, rng, ranges, primaries, formation_eq, secondaries, tr)
                                for k in range(m))
        p = _phreeqc(backend.db)
        if p.RunString(inp):
            raise RuntimeError(p.GetErrorString()[:2000])
        out = p.GetSelectedOutput()
        last: Dict[int, int] = {}
        for i, sm in enumerate(out["sim"]):
            last[int(sm)] = i
        for i in last.values():
            x = [np.log10(max(float(out[f"m_{e}"][i]), 10 ** LOG_FLOOR)) for e in els]
            x += [float(out["temp(C)"][i]) + 273.15, float(out["P"][i]) * ATM]
            y = [float(out["pH"][i])] + [float(out[f"si_{ph}"][i]) for ph in phases]
            if np.all(np.isfinite(y)) and min(y[1:]) > -900:
                X.append(x); Y.append(y)
        done += m
    return {"X": np.array(X), "Y": np.array(Y), "elements": list(els), "phases": list(phases)}


# ----------------------------------------------------------------------
# 2. A small NumPy MLP
# ----------------------------------------------------------------------
class MLP:
    def __init__(self, sizes: Sequence[int], rng: np.random.Generator):
        self.W = [rng.normal(0, np.sqrt(2.0 / a), (a, b)) for a, b in zip(sizes[:-1], sizes[1:])]
        self.b = [np.zeros(b) for b in sizes[1:]]
        self.x_mu = self.x_sd = self.y_mu = self.y_sd = None

    def _forward(self, z):
        hs = [z]
        for i, (W, b) in enumerate(zip(self.W, self.b)):
            z = z @ W + b
            if i < len(self.W) - 1:
                z = np.tanh(z)
            hs.append(z)
        return hs

    def predict(self, X):
        z = (X - self.x_mu) / self.x_sd
        return self._forward(z)[-1] * self.y_sd + self.y_mu

    def state_dict(self):
        return dict(W=[w.copy() for w in self.W], b=[b.copy() for b in self.b],
                    x_mu=self.x_mu, x_sd=self.x_sd, y_mu=self.y_mu, y_sd=self.y_sd)

    def save(self, path):
        """Portable .npz (no pickle)."""
        d = {f"W{i}": w for i, w in enumerate(self.W)}
        d.update({f"b{i}": b for i, b in enumerate(self.b)})
        np.savez(path, x_mu=self.x_mu, x_sd=self.x_sd, y_mu=self.y_mu, y_sd=self.y_sd, **d)

    @classmethod
    def load(cls, path):
        z = np.load(path, allow_pickle=False)
        nl = sum(1 for k in z.files if k.startswith("W"))
        return cls.from_state(dict(W=[z[f"W{i}"] for i in range(nl)], b=[z[f"b{i}"] for i in range(nl)],
                                   x_mu=z["x_mu"], x_sd=z["x_sd"], y_mu=z["y_mu"], y_sd=z["y_sd"]))

    @classmethod
    def from_state(cls, d):
        m = cls.__new__(cls)
        m.W, m.b = [np.asarray(w) for w in d["W"]], [np.asarray(b) for b in d["b"]]
        m.x_mu, m.x_sd, m.y_mu, m.y_sd = (np.asarray(d[k]) for k in ("x_mu", "x_sd", "y_mu", "y_sd"))
        return m


def fit_mlp(X, Y, hidden=(96, 96, 96), epochs=400, batch=256, lr=2e-3, seed=0,
            val_frac=0.1, verbose=False):
    """Adam on mean-squared error of standardised targets; keeps the best
    validation epoch.  Returns (model, history)."""
    rng = np.random.default_rng(seed)
    n = X.shape[0]
    idx = rng.permutation(n)
    nv = int(val_frac * n)
    vi, ti = idx[:nv], idx[nv:]
    m = MLP([X.shape[1], *hidden, Y.shape[1]], rng)
    m.x_mu, m.x_sd = X[ti].mean(0), X[ti].std(0) + 1e-12
    m.y_mu, m.y_sd = Y[ti].mean(0), Y[ti].std(0) + 1e-12
    Xs, Ys = (X - m.x_mu) / m.x_sd, (Y - m.y_mu) / m.y_sd
    params = m.W + m.b
    mom = [np.zeros_like(p) for p in params]
    vel = [np.zeros_like(p) for p in params]
    t, best, best_state, hist = 0, np.inf, None, []
    for ep in range(epochs):
        lr_ep = lr * 0.5 * (1 + np.cos(np.pi * ep / epochs))   # cosine decay
        perm = rng.permutation(ti)
        for s in range(0, len(perm), batch):
            bi = perm[s:s + batch]
            hs = m._forward(Xs[bi])
            g = 2.0 * (hs[-1] - Ys[bi]) / len(bi)
            gW, gb = [None] * len(m.W), [None] * len(m.b)
            for L in range(len(m.W) - 1, -1, -1):
                gW[L] = hs[L].T @ g
                gb[L] = g.sum(0)
                if L:
                    g = (g @ m.W[L].T) * (1.0 - hs[L] ** 2)
            t += 1
            for p, gp, mo, ve in zip(params, gW + gb, mom, vel):
                mo *= 0.9; mo += 0.1 * gp
                ve *= 0.999; ve += 0.001 * gp * gp
                p -= lr_ep * (mo / (1 - 0.9 ** t)) / (np.sqrt(ve / (1 - 0.999 ** t)) + 1e-8)
        vloss = float(np.mean((m._forward(Xs[vi])[-1] - Ys[vi]) ** 2))
        hist.append(vloss)
        if vloss < best:
            best, best_state = vloss, m.state_dict()
        if verbose and ep % 50 == 0:
            print(f"epoch {ep}: val mse {vloss:.3e}")
    return MLP.from_state(best_state), hist


# ----------------------------------------------------------------------
# 3. Surrogate model for SurrogateBackend
# ----------------------------------------------------------------------
# Formal charge of the conservative ions; Al, Si and C are left out (their
# charge depends on speciation).  The charge excess sets the carbonate
# alkalinity and hence pH, which is the steepest map the network must learn.
ION_CHARGE = {"Na": 1, "K": 1, "Li": 1, "Mg": 2, "Ca": 2, "Fe": 2, "Sr": 2, "Ba": 2, "Cl": -1, "Br": -1}


def add_charge_feature(X, elements, scale=1e5):
    """Append asinh(scale * sum_i z_i m_i) to raw features [log10 m, T, P]."""
    ne = len(elements)
    m = 10.0 ** X[:, :ne]
    z = np.array([ION_CHARGE.get(e, 0) for e in elements], float)
    return np.column_stack([X, np.arcsinh(scale * (m @ z))])


def positivity_limit(xi, n_aq, n_min, nu):
    """Scale precipitation (xi < 0) jointly so that no element goes negative,
    and cap dissolution at the mineral present.  Exact and cheap; shared
    elements (Al, Si between feldspars and kaolinite) are handled together."""
    xi = np.minimum(xi, n_min)
    dis = np.clip(xi, 0, None)
    pre = np.clip(-xi, 0, None)
    supply = n_aq + dis @ nu                        # (n, ncomp) available
    demand = pre @ nu
    with np.errstate(divide="ignore", invalid="ignore"):
        ratio = np.where(demand > 0, np.clip(supply, 0, None) / demand, np.inf)
    alpha = np.minimum(1.0, ratio.min(axis=1))[:, None]
    return dis - pre * alpha


class SpeciationSurrogate:
    """Callable ``model(x: ChemInput, mode)`` for chemistry.SurrogateBackend.

    * kinetic: the PK rate law is integrated with ``nsub`` explicit substeps,
      re-speciating with the network at every substep (so a silica release from
      feldspar can drive quartz precipitation within the step, as in the
      PHREEQC KINETICS reference).  Each substep is limited so the learned
      log Omega of a mineral does not cross zero (``limiter``) and so that no
      element or mineral goes negative (``positivity_limit``).
    * equilibrium: not learned; raises so that SurrogateBackend sends those
      cells to the reference.
    * ``speciate(x)`` mirrors PhreeqcBackend.speciate and can be used as the
      cheap checker in SurrogateBackend (``speciate_fn``).
    """

    def __init__(self, net: MLP, minerals, elements: Sequence[str], water_density=1000.0,
                 limiter: float = 0.8, nsub: int = 8, stiff_max: Optional[float] = None):
        self.net, self.minerals, self.elements = net, list(minerals), list(elements)
        self.rho_w = water_density
        self.limiter = limiter
        self.nsub = nsub
        # cells whose stiffness ratio exceeds stiff_max are routed to the
        # reference before the surrogate is applied (None: never)
        self.stiff_max = stiff_max
        self.nu = np.array([m.nu for m in self.minerals], float)

    def features(self, n_aq, v_brine, T, P):
        kgw = np.maximum(v_brine * self.rho_w, 1e-12)
        m = np.clip(n_aq / kgw[:, None], 10 ** LOG_FLOOR, None)
        return add_charge_feature(np.column_stack([np.log10(m), T, P]), self.elements)

    def _spec(self, n_aq, v_brine, T, P):
        y = self.net.predict(self.features(n_aq, v_brine, T, P))
        return y[:, 0], y[:, 1:]

    def speciate(self, x):
        return self._spec(x.n_aq, x.v_brine, x.T, x.P)

    def _steps_and_caps(self, n_aq, n_min, x, pH, si, h, area):
        kgw = np.maximum(x.v_brine * self.rho_w, 1e-12)
        m_el = np.clip(n_aq / kgw[:, None], 1e-14, None)
        step = np.zeros_like(n_min)
        cap = np.zeros_like(n_min)
        for j, mnl in enumerate(self.minerals):
            r = mineral_rate(mnl, area[:, j], x.T, pH, 10.0 ** si[:, j])
            step[:, j] = r * x.v_bulk * h
            # ideal free-ion estimate of d(log Omega)/d(xi) -> moles to equilibrium
            slope = (self.nu[j][None, :] ** 2 / (np.log(10) * m_el * kgw[:, None])).sum(1)
            cap[:, j] = np.abs(si[:, j]) / np.maximum(slope, 1e-300)
        return step, cap

    def stiffness(self, x: ChemInput) -> np.ndarray:
        """Per-cell stiffness ratio S = max_j |r_j dt| / (moles of mineral j to
        equilibrium), from the start-of-step state.  S >> 1 means the explicit
        surrogate would need more than S substeps (near-equilibrium cells
        coupled through a scarce element such as Al).  A priori: it needs only
        the learned speciation, no chemistry solve."""
        pH, si = self._spec(x.n_aq, x.v_brine, x.T, x.P)
        step, cap = self._steps_and_caps(x.n_aq, x.n_min, x, pH, si, x.dt, x.area)
        S = np.abs(step) / np.maximum(cap, 1e-300)
        return np.where(x.mask(), S, 0.0).max(axis=1)

    def __call__(self, x: ChemInput, mode: str):
        if mode != "kinetic":
            raise NotImplementedError("equilibrium cells use the reference backend")
        act = x.mask()
        stiff = (self.stiffness(x) > self.stiff_max) if self.stiff_max is not None else None
        n_aq, n_min = x.n_aq.copy(), x.n_min.copy()
        kgw = np.maximum(x.v_brine * self.rho_w, 1e-12)
        h = x.dt / self.nsub
        xi_tot = np.zeros_like(n_min)
        frac0 = np.where(x.n_min > 0, 1.0, 0.0)
        for _ in range(self.nsub):
            pH, si = self._spec(n_aq, x.v_brine, x.T, x.P)
            frac = np.divide(n_min, x.n_min, out=frac0.copy(), where=x.n_min > 0)
            area = x.area * np.clip(frac, 0, None) ** (2.0 / 3.0)
            step, cap = self._steps_and_caps(n_aq, n_min, x, pH, si, h, area)
            # do not move more than `limiter` of the way to log Omega = 0 per substep
            xi = np.sign(step) * np.minimum(np.abs(step), self.limiter * cap)
            xi = positivity_limit(np.where(act, xi, 0.0), n_aq, n_min, self.nu)
            n_aq += xi @ self.nu
            n_min -= xi
            xi_tot += xi
        out = {"xi": xi_tot}
        if stiff is not None:
            out["route_to_reference"] = stiff
        return out
