def load_json(path: Path):
    if not path.exists():
        raise FileNotFoundError(f"Missing prerequisite:\n{path}")
    return json.loads(path.read_text(encoding="utf-8"))


def load_csv(path: Path):
    if not path.exists():
        return []
    with path.open("r", newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def save_json(path: Path, payload):
    path.write_text(json.dumps(payload, indent=2), encoding="utf-8")


def save_csv(path: Path, rows):
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    fields = []
    for row in rows:
        for k in row:
            if k not in fields:
                fields.append(k)
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)


def safe_text(path: Path):
    try:
        return path.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return ""


def sha256_file(path: Path):
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def sha256_array(arr):
    a = np.ascontiguousarray(arr)
    return hashlib.sha256(a.tobytes()).hexdigest()


def float32_envelope(arr):
    """
    Conservative precision-aware envelope derived from float32 spacing.
    """
    a = np.asarray(arr, dtype=np.float32)
    if a.size == 0:
        return 0.0
    spacing = np.spacing(a)
    half_ulp = np.nanmax(np.abs(spacing)) / 2.0
    return float(max(2.0 * half_ulp, 1e-12))


def candidate_100d_rows():
    inv = load_csv(R17_STATE_INV)
    tmap = load_csv(R17_TIME_MAP)

    time_by_hash = defaultdict(set)
    for r in tmap:
        h = r.get("array_sha256", "")
        for x in r.get("provenance_time_candidates", "").split(";"):
            if not x:
                continue
            try:
                time_by_hash[h].add(float(x))
            except Exception:
                pass

    out = []
    for r in inv:
        h = r.get("array_sha256", "")
        if any(abs(t - TARGET_TIME_DAYS) <= 1e-12 for t in time_by_hash.get(h, set())):
            out.append(r)
    return out


def load_array_from_inventory_row(row):
    p = Path(row["artifact_path"])
    key = row["key"]

    if not p.exists():
        return None

    db = np.load(p, allow_pickle=True)
    try:
        arr = np.asarray(db[key])
    except Exception:
        db.close()
        return None

    arr = np.array(arr, copy=True)
    db.close()
    return arr


def infer_replay_state_from_persisted_contract():
    """
    R19 must be robust to source architecture. We reconstruct the replay state
    from the persisted validated R1F3 artifact if it contains an explicit 100d
    state; otherwise return None and let source binding determine next branch.

    This does NOT select by SG7E performance.
    """
    if not R1F3_FROZEN.exists():
        return None, None

    db = np.load(R1F3_FROZEN, allow_pickle=True)

    preferred_keys = [
        "candidate_state_100d",
        "state_100d",
        "L2_state_100d",
        "candidate_100d",
        "saturation_100d",
        "L2",
        "candidate_state",
        "state",
    ]

    for key in preferred_keys:
        if key in db.files:
            arr = np.asarray(db[key])
            if arr.shape == EXPECTED_STATE_SHAPE:
                out = np.array(arr, copy=True)
                db.close()
                return out, key

    # Fallback: if exactly one plausible (2662,201) array has an explicit 100
    # marker in its key, use that as replay target.
    candidates = []
    for key in db.files:
        arr = np.asarray(db[key])
        if arr.shape == EXPECTED_STATE_SHAPE and "100" in key.lower():
            candidates.append((key, np.array(arr, copy=True)))

    db.close()

    if len(candidates) == 1:
        return candidates[0][1], candidates[0][0]

    return None, None


